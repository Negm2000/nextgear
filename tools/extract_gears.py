"""Regenerate src/nextgear/fabric_gears.py from a constructorfabric/gears-rust checkout.

Every gear in gears-rust declares its dependencies in a `#[toolkit::gear(name = ..., deps = [...])]`
attribute. This script reads those attributes for the gears Nextgear simulates and their transitive
dependencies, and writes them out with the commit they came from.

    git clone https://github.com/constructorfabric/gears-rust
    git -C gears-rust checkout fc765feb8e328ae31c44bfb3a0c981b42e32a105
    python tools/extract_gears.py gears-rust
"""

import re
import subprocess
import sys
from pathlib import Path

# The gears Nextgear's agent can propose. Their dependencies are added automatically below.
SIMULATED = ("api-gateway", "authn-resolver", "policy-engine", "license-resolver", "chat-engine", "bss-ledger",
             "serverless-runtime", "tenant-resolver", "usage-collector", "oagw")
OUT = Path(__file__).resolve().parents[1] / "src" / "nextgear" / "fabric_gears.py"


def declarations(root: Path) -> dict[str, tuple[tuple[str, ...], str]]:
    """Gear name -> (declared dependencies, source file), from every gear attribute under gears/."""
    found = {}
    for path in sorted((root / "gears").rglob("*.rs")):
        if "tests" in path.parts:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for match in re.finditer(r"#\[(?:toolkit::)?gear\(", text):
            depth, end = 1, match.end()
            while depth:
                depth += {"(": 1, ")": -1}.get(text[end], 0)
                end += 1
            body = " ".join(text[match.end():end - 1].split())
            name = re.search(r'\bname\s*=\s*"([^"]+)"', body)
            if not name:
                continue
            deps = re.search(r"\bdeps\s*=\s*\[([^\]]*)\]", body)
            # The gear macro turns each dependency identifier into a name by replacing '_' with '-'.
            names = tuple(d.strip().replace("_", "-") for d in deps.group(1).split(",") if d.strip()) if deps else ()
            found.setdefault(name.group(1), (names, path.relative_to(root).as_posix()))
    return found


def main(root: Path) -> None:
    commit = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"], capture_output=True, text=True,
                            check=True).stdout.strip()
    found = declarations(root)
    keep, queue = {}, list(SIMULATED)
    while queue:
        gear = queue.pop(0)
        if gear in keep:
            continue
        keep[gear] = found.get(gear)
        queue += list(keep[gear][0]) if keep[gear] else []
    lines = [
        '"""Gear dependencies declared in constructorfabric/gears-rust. Generated by tools/extract_gears.py; do not edit."""',
        "",
        'SOURCE = "https://github.com/constructorfabric/gears-rust"',
        f'COMMIT = "{commit}"',
        "",
        "# Gear name -> the `deps` of its #[toolkit::gear(...)] declaration, with the declaring file.",
        "# Gears that have no declaration at this commit are listed in UNDECLARED.",
        "DEPS: dict[str, tuple[str, ...]] = {",
    ]
    for gear, entry in keep.items():
        if entry:
            deps, source = entry
            lines += [f"    # {source}", f"    {gear!r}: {deps!r},"]
    lines += ["}", "", "UNDECLARED: tuple[str, ...] = " + repr(tuple(g for g, e in keep.items() if not e)), ""]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT} from {commit}: {len(keep)} gears")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]))
